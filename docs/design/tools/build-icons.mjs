// Builds prototype/assets/icons.js, the icon sprite, from the Phosphor SVGs in docs/design/icons/.
// Phosphor Icons 2.1.1 (https://phosphoricons.com), MIT licence (icons/LICENSE-Phosphor-MIT.txt).
// Regular weight is the default; fill weight is used for the current tab and a few status marks.
//   node docs/design/tools/build-icons.mjs
// In the real app, import the same icons from `@phosphor-icons/core` (or inline these SVGs): no new
// icon drawings are made for Sabi except the logo.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';

const D = join(dirname(fileURLToPath(import.meta.url)), '..');
// Only icons the prototype uses are included (a name written as a string in one of these files), so the
// sprite stays small. Fill versions are included when the base name is used and the code asks for '-fill'.
const SOURCES = ['ui.js', 'map.js', 'art.js', 'screens-app.js', 'screens-user.js', 'screens-admin.js', 'screens-sys.js', 'sample.js'].map((f) => readFileSync(join(D, 'prototype', 'assets', f), 'utf8')).join(' ');
const used = (name, fill) => new RegExp(`['"\`]${name}${fill ? '-fill' : ''}['"\`]`).test(SOURCES) || (fill && new RegExp(`['"\`]${name}['"\`]`).test(SOURCES) && /-fill/.test(SOURCES));
const symbols = [];
for (const weight of ['regular', 'fill']) {
  for (const f of readdirSync(join(D, 'icons', weight)).filter((x) => x.endsWith('.svg')).sort()) {
    const svg = readFileSync(join(D, 'icons', weight, f), 'utf8');
    const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim();
    const name = f.replace('.svg', '');
    if (!used(weight === 'fill' ? name.replace(/-fill$/, '') : name, weight === 'fill')) continue;
    symbols.push(`<symbol id="i-${name}" viewBox="0 0 256 256">${inner}</symbol>`);
  }
}
const sprite = `<svg xmlns="http://www.w3.org/2000/svg" width="0" height="0" style="position:absolute" aria-hidden="true" focusable="false">${symbols.join('')}</svg>`;
const out = `// Generated by tools/build-icons.mjs from Phosphor Icons 2.1.1 (MIT). Do not edit by hand.
window.SABI_ICON_SPRITE = ${JSON.stringify(sprite)};
`;
writeFileSync(join(D, 'prototype', 'assets', 'icons.js'), out);
console.log(`icons.js: ${symbols.length} icons, ${(out.length / 1024).toFixed(1)} KB, ${(gzipSync(Buffer.from(out), { level: 9 }).length / 1024).toFixed(1)} KB gzipped`);
